// Ensure vmResource satisfies the resource.Resource and
// resource.ResourceWithImportState interfaces.
var (
	_ resource.Resource                = &vmResource{}
	_ resource.ResourceWithImportState = &vmResource{}
)

// vmResourceModel maps the schema attributes for exedev_vm.
type vmResourceModel struct {
	// ID is the VM name (used as stable identifier in state).
	ID types.String `tfsdk:"id"`
	// Name is the VM name. Optional; exe.dev auto-generates one if omitted.
	Name types.String `tfsdk:"name"`
	// Image is the container image (e.g. "ubuntu:22.04").
	Image types.String `tfsdk:"image"`
	// Disk is the disk size at creation (e.g. "20GB"). Can be grown with resize.
	Disk types.String `tfsdk:"disk"`
	// Command overrides the default container start command.
	Command types.String `tfsdk:"command"`
	// Env is a map of KEY=VALUE environment variables.
	Env types.Map `tfsdk:"env"`
	// Integrations is a list of integration names to attach.
	Integrations types.List `tfsdk:"integrations"`
	// SetupScript is a script to run on first boot.
	SetupScript types.String `tfsdk:"setup_script"`
	// Hostname is the computed public hostname (name.exe.xyz).
	Hostname types.String `tfsdk:"hostname"`
	// Status is the computed VM status (running, stopped, etc.).
	Status types.String `tfsdk:"status"`
	// Region is the computed region where the VM was placed.
	Region types.String `tfsdk:"region"`
}

// vmAPIResponse is used to decode the JSON returned by exe.dev commands.
// Fields match the actual JSON keys returned by the ls --json command.
type vmAPIResponse struct {
	// ls --json returns vm_name; new --json may return name
	VMName   string `json:"vm_name"`
	Name     string `json:"name"`
	HTTPSURL string `json:"https_url"`
	Image    string `json:"image"`
	// disk_capacity_bytes is returned as an integer number of bytes
	DiskCapacityBytes int64  `json:"disk_capacity_bytes"`
	Status            string `json:"status"`
	Region            string `json:"region"`
	SSHDest           string `json:"ssh_dest"`
}

// effectiveName returns the VM name from whichever field is populated.
func (v vmAPIResponse) effectiveName() string {
	if v.VMName != "" {
		return v.VMName
	}
	return v.Name
}

// effectiveHostname returns the public hostname from the API response.
func (v vmAPIResponse) effectiveHostname() string {
	if v.HTTPSURL != "" {
		// strip the scheme to get just the hostname
		h := v.HTTPSURL
		if len(h) > 8 && h[:8] == "https://" {
			h = h[8:]
		}
		return h
	}
	if v.SSHDest != "" {
		return v.SSHDest
	}
	return v.effectiveName() + ".exe.xyz"
}

// vmListResponse is the envelope returned by ls --json.
type vmListResponse struct {
	VMs []vmAPIResponse `json:"vms"`
}

// vmResource is the concrete resource implementation.
type vmResource struct {
	client *client.Client
}

// NewVMResource returns a new vmResource factory function.
func NewVMResource() resource.Resource {
	return &vmResource{}
}

